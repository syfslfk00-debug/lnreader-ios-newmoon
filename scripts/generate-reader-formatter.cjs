// Hermes does not retain Function#toString source in Release. Generate the
// WebView copy at build time from the SAME formatter used by the RN renderer.
const fs = require('fs');
const path = require('path');
const ts = require('typescript');
const sourcePath = path.join(__dirname, '../src/reader/newmoon/sections.ts');
const destination = path.join(
  __dirname,
  '../src/reader/newmoon/formatterSource.ts',
);
const source = fs.readFileSync(sourcePath, 'utf8');
const start = source.indexOf('export const createLineFormatter =');
const end = source.indexOf('export const processLineHTML =', start);
if (start < 0 || end < 0) throw new Error('Formatter factory not found');
const compiled = ts
  .transpileModule(source.slice(start, end).replace('export const', 'const'), {
    compilerOptions: { target: ts.ScriptTarget.ES2020, removeComments: true },
  })
  .outputText.trim();
const expression = compiled
  .slice(compiled.indexOf('=') + 1)
  .trim()
  .replace(/;$/, '');
const output =
  '// prettier-ignore\n// Generated by scripts/generate-reader-formatter.cjs. Do not edit.\n' +
  'export const LINE_FORMATTER_SOURCE = ' +
  JSON.stringify('(' + expression + ')()') +
  ';\n';
if (process.argv.includes('--check')) {
  if (
    !fs.existsSync(destination) ||
    fs.readFileSync(destination, 'utf8') !== output
  ) {
    throw new Error(
      'Reader formatter is stale. Run pnpm run generate:reader-formatter.',
    );
  }
} else fs.writeFileSync(destination, output);
